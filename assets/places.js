const HOURS = { '1시간대': 1, '2시간대': 2, '3시간대': 3, '4시간대': 4, '5시간대': 5 };
export const RAINY_MM = 200; // 이 이상이면 '비가 많은 달'로 표시

// 해당 월(1~12)의 요약
export function climate(id, month) {
  const p = PLACES[id];
  if (!p) return null;
  const i = month - 1;
  return { hi: Math.round(p.hi[i]), lo: Math.round(p.lo[i]), rain: Math.round(p.rain[i]), rainy: p.rain[i] >= RAINY_MM, typhoon: p.typhoon && month >= 7 && month <= 9 };
}

// 연휴 길이와 그 달 날씨로 고른 추천 목적지 (규칙 기반, 점수는 정렬용)
// - 3~4일: 비행 3시간 미만만, 5~6일: 4시간 미만, 7일 이상: 전체 (먼 곳 가점)
// - 평균기온(최고·최저 평균)이 15~27도면 가점, 비가 많은 달·태풍철은 감점
export function recommend(ids, length, month) {
  const maxH = length <= 4 ? 2 : length <= 6 ? 3 : 5;
  return ids
    .filter((id) => PLACES[id] && HOURS[PLACES[id].flight] <= maxH)
    .map((id) => {
      const c = climate(id, month);
      const mean = (c.hi + c.lo) / 2;
      let score = 0;
      score += mean >= 15 && mean <= 27 ? 3 : mean >= 10 && mean <= 30 ? 1 : -1;
      if (c.rainy) score -= 2;
      if (c.typhoon) score -= 1;
      if (length >= 7) score += HOURS[PLACES[id].flight] * 0.4;
      return { id, score, c };
    })
    .sort((a, b) => b.score - a.score);
}

export function tzText(tz) {
  return tz === 0 ? '시차 없음' : `한국보다 ${Math.abs(tz)}시간 ${tz < 0 ? '느림' : '빠름'}`;
}
